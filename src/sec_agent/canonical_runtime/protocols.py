from __future__ import annotations

from contextlib import AbstractContextManager
from typing import Any, Mapping, Protocol, Sequence

from .models import EventEnvelope


class CanonicalTransaction(Protocol):
    def insert(self, table: str, logical_id: str, version: int, payload: Mapping[str, Any]) -> None: ...
    def append_event(self, event: EventEnvelope) -> None: ...
    def put_idempotency(self, scope_key: str, payload_digest: str, result: Mapping[str, Any]) -> None: ...
    def get_idempotency(self, scope_key: str) -> Mapping[str, Any] | None: ...
    def next_event_sequence(self, task_run_id: str | None) -> int: ...
    def get_latest(self, table: str, logical_id: str) -> Mapping[str, Any] | None: ...
    def list_latest(self, table: str, *, case_id: str | None = None) -> Sequence[Mapping[str, Any]]: ...
    def list_versions(self, table: str, *, case_id: str | None = None) -> Sequence[Mapping[str, Any]]: ...
    def assert_expected_state(self, table: str, logical_id: str, expected: int) -> None: ...


class CanonicalStore(Protocol):
    def transaction(self, *, rollback_control: bool = False) -> AbstractContextManager[CanonicalTransaction]: ...
    def get_latest(self, table: str, logical_id: str) -> Mapping[str, Any] | None: ...
    def get_version(self, table: str, logical_id: str, version: int) -> Mapping[str, Any] | None: ...
    def list_latest(self, table: str, *, case_id: str | None = None) -> Sequence[Mapping[str, Any]]: ...
    def list_versions(self, table: str, *, case_id: str | None = None, version: int | None = None) -> Sequence[Mapping[str, Any]]: ...
    def list_events(self, task_run_id: str | None = None) -> Sequence[Mapping[str, Any]]: ...
    def set_kill_switch(self, enabled: bool) -> None: ...
    def kill_switch_enabled(self) -> bool: ...
    def recovery_check(self) -> Mapping[str, Any]: ...
    def store_identity(self) -> str: ...
    def content_fingerprint(self) -> str: ...


class CanonicalObjectStore(Protocol):
    def put_json(self, payload: Any, *, namespace: str, artifact_type: str) -> Mapping[str, Any]: ...
    def get_json(self, object_key: str, *, expected_digest: str | None = None) -> Any: ...


class ExternalCallObserver(Protocol):
    def record(self, call_type: str) -> None: ...
