"""Host-selected research effort, independent of permission and financial limits."""

DEPTHS = {
    'brief': '快速追踪：核清消息、时间与主要事实，给出有归属的解释线索。尚未展开的关系明确留作后续研究，不将其写成已验证的投资结论。',
    'standard': '常规研究：围绕主判断核对原始依据与必要的传导关系。优先解决足以改变答案的未知，取得足够依据后交付，不扩写无关背景。',
    'deep': '深入研究：对会改变主判断的未知继续调查，直到已取得能区分主要解释的观察，或能够指出合理可得公开资料的具体边界。'
        '先利用现有原件、相关主体的正式披露和公开数据，再按缺口找替代原件或独立来源；搜索失败是取证障碍，不是信息边界。'
        '“查过”须是实际读取相关内容；搜索摘要和重复转载不算新的独立核查。'
        '优先查不同结果会改变判断的关系，不要求穷尽互联网、每家公司或所有可能原因。'
        '若继续查询只会重复同一事实，或关键数据由私有合同/尚未发生的事件决定，说明已知结果、具体缺口及条件化判断即可结束。'
        '把改变认识的发现和仍待查的关键关系更新到现有工作记录；交付前处理这些关系，不能将未执行的调查改称未披露。'
        '独立 Agent 可调查一个关键分歧或挑战核心解释，主作者继续其他有价值的工作；篇幅、Agent 数和调用数都不是深度目标。',
}


def depth_guidance(depth='standard'):
    if depth not in DEPTHS:
        raise ValueError('unknown_research_depth')
    return ('\n\n当前研究深度：' + depth + '。' + DEPTHS[depth]
            + '\n各深度的时点核验和必要外部依据相同；深度改变探索宽度、比较与验证力度，不允许以过时知识替代当前事实。'
            + '\n实际工具授权与预算另由宿主管理，深度选择不增加权限或额度。\n')
